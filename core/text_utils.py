def to_simplified(text: str) -> str:
    """将繁体中文转为简体中文。"""
    if not text:
        return ""
    norm = unicodedata.normalize("NFKC", text)
    return norm.translate(_T2S_DICT)


def to_traditional(text: str) -> str:
    """将简体中文转为常见繁体中文（用于繁体漫画源关键词二次检索兜底）。"""
    if not text:
        return ""
    norm = unicodedata.normalize("NFKC", text)
    return norm.translate(_S2T_DICT)


def normalize_for_match(text: str) -> str:
    """将标题归一化为紧凑简体小写无标点串，用于跨源高精度对比。"""
    if not text:
        return ""
    simp = to_simplified(text).lower()
    cleaned = _NON_WORD_RE.sub("", simp)
    return cleaned.replace("_", "")


def dice_coefficient(a: str, b: str) -> float:
    """计算两个归一化字符串的 2-gram Sørensen–Dice 相似度 (0.0~1.0)。"""
    if not a or not b:
        return 0.0
    if a == b:
        return 1.0
    if len(a) == 1 or len(b) == 1:
        return 1.0 if (a in b or b in a) else 0.0
    bigrams_a = {a[i : i + 2] for i in range(len(a) - 1)}
    bigrams_b = {b[i : i + 2] for i in range(len(b) - 1)}
    overlap = len(bigrams_a & bigrams_b)
    return (2.0 * overlap) / (len(bigrams_a) + len(bigrams_b))


def score_title_match(
    query: str,
    title: str,
    aliases: list[str] | None = None,
) -> float:
    """计算用户输入的漫画名与候选词条的综合匹配度 (0.0 ~ 1.0)。"""
    q_norm = normalize_for_match(query)
    if not q_norm:
        return 0.0

    best = 0.0
    candidates = [(title, 0.0)]
    for al in aliases or []:
        if al:
            candidates.append((al, 0.02))

    for cand_text, penalty in candidates:
        c_norm = normalize_for_match(cand_text)
        if not c_norm:
            continue
        if q_norm == c_norm:
            score = 1.0 - penalty
        elif c_norm.startswith(q_norm):
            ratio = len(q_norm) / len(c_norm)
            score = 0.86 + 0.10 * ratio - penalty
        elif q_norm in c_norm:
            ratio = len(q_norm) / len(c_norm)
            score = 0.76 + 0.14 * ratio - penalty
        elif c_norm in q_norm and len(c_norm) >= 2:
            ratio = len(c_norm) / len(q_norm)
            score = 0.70 + 0.14 * ratio - penalty
        else:
            score = dice_coefficient(q_norm, c_norm) * 0.78 - penalty
        if score > best:
            best = score

    return max(0.0, min(1.0, best))


def parse_chinese_integer(text: str) -> int | None:
    """解析中文数字（如 '一' -> 1, '十二' -> 12, '一百零五' -> 105, '二〇三' -> 203）。"""
    s = (text or "").strip()
    if not s:
        return None
    if all(ch in _CN_DIGITS for ch in s):
        val = 0
        for ch in s:
            val = val * 10 + _CN_DIGITS[ch]
        return val

    total = 0
    current = 0
    has_any = False
    for ch in s:
        if ch in _CN_DIGITS:
            current = _CN_DIGITS[ch]
            has_any = True
        elif ch in _CN_UNITS:
            unit = _CN_UNITS[ch]
            if current == 0:
                current = 1
            total += current * unit
            current = 0
            has_any = True
        else:
            return None
    return (total + current) if has_any else None


_ARABIC_NUM_RE = re.compile(r"(\d+(?:\.\d+)?)")
_CN_NUM_RE = re.compile(r"([零〇一壹二贰两兩三叁四肆五伍六陆七柒八捌九玖十拾百佰千仟]+)")


def extract_number_from_text(text: str) -> float | None:
    """从章节字符串（如 '第01话', '12.5话', '第一百二十话'）提取数值。"""
    if not text:
        return None
    s = unicodedata.normalize("NFKC", text)
    m = _ARABIC_NUM_RE.search(s)
    if m:
        try:
            return float(m.group(1))
        except ValueError:
            pass
    m_cn = _CN_NUM_RE.search(s)
    if m_cn:
        parsed = parse_chinese_integer(m_cn.group(1))
        if parsed is not None:
            return float(parsed)
    return None


def format_chapter_num(num: float) -> str:
    """格式化浮点数话数（1.0 -> '1', 12.5 -> '12.5'）。"""
    if num.is_integer():
        return str(int(num))
    return f"{num:g}"
